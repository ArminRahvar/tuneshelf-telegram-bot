    def add_track_to_collection(
        self, user_id: int, track_id: int, collection_id: int
    ) -> bool:
        with self._connection() as connection:
            source = connection.execute(
                """
                SELECT t.* FROM tracks t JOIN playlists p ON p.id = t.playlist_id
                WHERE t.id = %s AND p.user_id = %s
                """,
                (track_id, user_id),
            ).fetchone()
            target = connection.execute(
                "SELECT id FROM playlists WHERE id = %s AND user_id = %s",
                (collection_id, user_id),
            ).fetchone()
            if source is None or target is None:
                return False
            duplicate = connection.execute(
                """
                SELECT id FROM tracks WHERE playlist_id = %s AND (
                    (source_chat_id = %s AND source_message_id = %s)
                    OR (%s IS NOT NULL AND file_unique_id = %s)
                ) LIMIT 1
                """,
                (
                    collection_id, source["source_chat_id"], source["source_message_id"],
                    source["file_unique_id"], source["file_unique_id"],
                ),
            ).fetchone()
            if duplicate is not None:
                return False
            inserted = connection.execute(
                """
                INSERT INTO tracks (
                    playlist_id, source_chat_id, source_message_id, title, performer,
                    media_type, file_unique_id, release_title, musicbrainz_recording_id,
                    telegram_file_id, duration_seconds, mime_type, original_filename,
                    rating, note
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    collection_id, source["source_chat_id"], source["source_message_id"],
                    source["title"], source["performer"], source["media_type"],
                    source["file_unique_id"], source["release_title"],
                    source["musicbrainz_recording_id"], source["telegram_file_id"],
                    source["duration_seconds"], source["mime_type"],
                    source["original_filename"], source["rating"], source["note"],
                ),
            ).fetchone()
            new_track_id = inserted["id"]
            references = connection.execute(
                """
                SELECT source_chat_id, source_message_id, telegram_file_id,
                       telegram_file_unique_id, media_type, original_filename,
                       last_verified_at, is_available
                FROM telegram_message_references
                WHERE track_id = %s AND owner_user_id = %s
                """,
                (track_id, user_id),
            ).fetchall()
            for reference in references:
                connection.execute(
                    """
                    INSERT INTO telegram_message_references (
                        track_id, owner_user_id, source_chat_id, source_message_id,
                        telegram_file_id, telegram_file_unique_id, media_type,
                        original_filename, last_verified_at, is_available
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        new_track_id, user_id, reference["source_chat_id"],
                        reference["source_message_id"], reference["telegram_file_id"],
                        reference["telegram_file_unique_id"], reference["media_type"],
                        reference["original_filename"], reference["last_verified_at"],
                        reference["is_available"],
                    ),
                )
            tags = connection.execute(
                """
                SELECT tag.id FROM tags tag JOIN track_tags tt ON tt.tag_id = tag.id
                WHERE tt.track_id = %s AND tag.owner_user_id = %s
                """,
                (track_id, user_id),
            ).fetchall()
            for tag in tags:
                connection.execute(
                    "INSERT INTO track_tags(track_id, tag_id) VALUES (%s, %s)",
                    (new_track_id, tag["id"]),
                )
            return True

